'''
Default locations of simulation outputs and external data.

Every path can be overridden with an environment variable, so that the
simulation scripts run unchanged on any machine:

    ZEBRAFISH_SNN_RESULTS
        Raw outputs written by the simulations.
        Default: <repository>/simulation_results

    ZEBRAFISH_SNN_ANALYSIS
        Curated simulation outputs (moved out of RESULTS_PATH by the
        ``move_results_*`` scripts) that are read by the post-processing scripts.
        Default: <RESULTS_PATH>/analysis

    ZEBRAFISH_SNN_WATER_DYNAMICS
        Pre-computed flow fields generated by the leader fish
        (see run_sim_files/README.md).
        Default: <RESULTS_PATH>/fluid_solver/saved_simulations
'''

import os

PACKAGEDIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

RESULTS_PATH = os.environ.get(
    'ZEBRAFISH_SNN_RESULTS',
    os.path.join(PACKAGEDIR, 'simulation_results'),
)

ANALYSIS_PATH = os.environ.get(
    'ZEBRAFISH_SNN_ANALYSIS',
    os.path.join(RESULTS_PATH, 'analysis'),
)

WATER_DYNAMICS_PATH = os.environ.get(
    'ZEBRAFISH_SNN_WATER_DYNAMICS',
    os.path.join(RESULTS_PATH, 'fluid_solver', 'saved_simulations'),
)
